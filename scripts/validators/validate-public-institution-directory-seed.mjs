import fs from "node:fs";
import path from "node:path";

const root=process.cwd();
const p=path.join(root,"manifests/institutions/seed/public-universities-and-tvet-2026-10-31.json");
const data=JSON.parse(fs.readFileSync(p,"utf8"));
const failed=[];
const check=(name,value)=>{const ok=Boolean(value);console.log((ok?"PASS ":"FAIL ")+name);if(!ok)failed.push(name)};
const records=data.records||[];
const univers=records.filter(x=>x.provider_type==="PUBLIC_UNIVERSITY");
const tvet=records.filter(x=>x.provider_type==="TVET_COLLEGE");
check("schema version",data.schema==="kingsmen.institutions.initial-public-directory-seed.v1");
check("expected 26 public universities",univers.length===26);
check("expected 50 TVET colleges",tvet.length===50);
check("total 76 directory entries",records.length===76);
check("stable refs unique",new Set(records.map(x=>x.institution_ref)).size===records.length);
check("names unique after normalization",new Set(records.map(x=>x.canonical_name.normalize("NFKC").toLowerCase().replace(/[^a-z0-9]+/g," ").trim())).size===records.length);
check("source coverage only uses official DHET pages",records.every(x=>x.directory_source_url.startsWith("https://www.dhet.gov.za/")));
check("entries do not claim partner or connected",records.every(x=>x.partnership_status==="NOT_A_PARTNER"&&x.integration_status==="NOT_CONNECTED"&&x.automation_authorized===false));
check("no intake/deadline/eligibility assumption",records.every(x=>x.intake_status==="UNKNOWN"&&x.deadline_status==="UNKNOWN"&&x.eligibility_status==="UNKNOWN"));
check("no programme/accreditation assumption",records.every(x=>x.programme_existence_status==="NOT_VERIFIED"&&x.accreditation_or_delivery_scope_status==="NOT_VERIFIED"));
check("all records preserve source evidence",records.every(x=>x.source_observations.length>0&&x.source_observations.every(o=>o.evidence_scope==="directory entry only"&&o.checked_at==="2026-10-31")));
check("every missing site remains a review item",records.filter(x=>!x.official_website_url).every(x=>x.official_website_status==="MISSING_OR_CONFLICTING_URL_REQUIRES_REVIEW"));
check("non-null website URLs are HTTPS",records.filter(x=>x.official_website_url).every(x=>x.official_website_url.startsWith("https://")));
check("UNISA link conflict surfaced",records.find(x=>x.institution_ref==="university-unisa")?.official_website_url===null);
check("Flavius Mareka truncated URL is not guessed",records.find(x=>x.institution_ref==="tvet-flavius-mareka")?.official_website_url===null);
check("CET and private registers remain explicit follow-up coverage",data.counts.cet_colleges_to_import_from_registry===9&&data.counts.private_higher_education_institutions_to_import_from_registry===138&&data.counts.other_private_colleges_to_import_from_registry===146);
console.log("Public institution seed validation: "+(failed.length?"FAILED":"PASS")+" ("+failed.length+" failures)");
if(failed.length)process.exit(1);
